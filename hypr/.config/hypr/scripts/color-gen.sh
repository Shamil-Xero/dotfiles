#!/usr/bin/env bash

##
# color-gen.sh — Parse matugen output and write per-app color files
# Usage: color-gen.sh <wallpaper_path> [dark|light]
##

set -euo pipefail

WALLPAPER="${1:-}"
MODE="${2:-dark}"

ROFI_COLORS="$HOME/.config/rofi/colors/wallpaper.rasi"
WAYBAR_COLORS="$HOME/.config/waybar/colors.css"
SWAYNC_COLORS="$HOME/.config/swaync/colors.css"
HYPR_COLORS="$HOME/.config/hypr/themes/colors.lua"
HYPRLOCK_COLORS="$HOME/.config/hypr/themes/hyprlock-colors.conf"
THEME_CACHE="$HOME/.config/hypr/themes/.current"

if [[ -z "$WALLPAPER" || ! -f "$WALLPAPER" ]]; then
    echo "[color-gen] ERROR: Wallpaper not found: '$WALLPAPER'" >&2
    exit 1
fi

mkdir -p "$(dirname "$ROFI_COLORS")"
mkdir -p "$(dirname "$HYPR_COLORS")"

echo "[color-gen] Extracting colors from: $WALLPAPER (mode: $MODE)"

# Generate matugen JSON palette
JSON=$(matugen image "$WALLPAPER" --mode "$MODE" --json hex 2>/dev/null)

if [[ -z "$JSON" ]]; then
    echo "[color-gen] ERROR: matugen returned empty output" >&2
    exit 1
fi

# Helper: extract a color field from JSON using python3
get_color() {
    local field="$1"
    echo "$JSON" | python3 -c "
import sys, json
data = json.load(sys.stdin)
colors = data.get('colors', {})
scheme = colors.get('${MODE}', colors.get('dark', {}))
val = scheme.get('${field}', '#888888')
print(val if val else '#888888')
" 2>/dev/null || echo '#888888'
}

PRIMARY=$(get_color "primary")
ON_PRIMARY=$(get_color "on_primary")
PRIMARY_CONTAINER=$(get_color "primary_container")
ON_PRIMARY_CONTAINER=$(get_color "on_primary_container")
SECONDARY=$(get_color "secondary")
ON_SECONDARY=$(get_color "on_secondary")
TERTIARY=$(get_color "tertiary")
SURFACE=$(get_color "surface")
ON_SURFACE=$(get_color "on_surface")
SURFACE_VARIANT=$(get_color "surface_variant")
ON_SURFACE_VARIANT=$(get_color "on_surface_variant")
BACKGROUND=$(get_color "background")
ON_BACKGROUND=$(get_color "on_background")
ERROR=$(get_color "error")
OUTLINE=$(get_color "outline")
OUTLINE_VARIANT=$(get_color "outline_variant")
SURFACE_CONTAINER=$(get_color "surface_container")
SURFACE_CONTAINER_HIGH=$(get_color "surface_container_high")
SURFACE_CONTAINER_HIGHEST=$(get_color "surface_container_highest")
SURFACE_CONTAINER_LOW=$(get_color "surface_container_low")

echo "[color-gen] Primary: $PRIMARY | Background: $BACKGROUND | Surface: $SURFACE"

# Helper: strip # and append alpha for hyprland rgba() format
to_rgba() {
    local hex="${1#\#}"
    local alpha="${2:-ee}"
    echo "rgba(${hex}${alpha})"
}

# ── Rofi ─────────────────────────────────────────────────────────────────────
cat > "$ROFI_COLORS" << EOF
/**
 * Wallpaper-generated Color Palette for Rofi
 * Auto-generated by color-gen.sh — DO NOT EDIT MANUALLY
 * Source: $WALLPAPER
 **/

* {
    background:                  ${BACKGROUND}FF;
    background-alt:              ${SURFACE_CONTAINER}FF;
    background-surface:          ${SURFACE_CONTAINER_LOW}FF;
    foreground:                  ${ON_BACKGROUND}FF;
    foreground-alt:              ${ON_SURFACE_VARIANT}FF;
    selected:                    ${PRIMARY}FF;
    selected-text:               ${ON_PRIMARY}FF;
    active:                      ${SECONDARY}FF;
    urgent:                      ${ERROR}FF;
    border-color:                ${PRIMARY}FF;
}
EOF
echo "[color-gen] ✓ Rofi colors written"

# ── Waybar ────────────────────────────────────────────────────────────────────
cat > "$WAYBAR_COLORS" << EOF
/* Wallpaper-generated colors for Waybar
 * Auto-generated by color-gen.sh — DO NOT EDIT MANUALLY */

@define-color wb-bg              ${SURFACE_CONTAINER};
@define-color wb-bg-alt          ${SURFACE_CONTAINER_HIGH};
@define-color wb-fg              ${ON_SURFACE};
@define-color wb-fg-alt          ${ON_SURFACE_VARIANT};
@define-color wb-primary         ${PRIMARY};
@define-color wb-secondary       ${SECONDARY};
@define-color wb-tertiary        ${TERTIARY};
@define-color wb-urgent          ${ERROR};
@define-color wb-border          ${OUTLINE_VARIANT};
@define-color wb-active-ws       ${PRIMARY_CONTAINER};
@define-color wb-active-ws-text  ${ON_PRIMARY_CONTAINER};
EOF
echo "[color-gen] ✓ Waybar colors written"

# ── SwayNC ────────────────────────────────────────────────────────────────────
cat > "$SWAYNC_COLORS" << EOF
/* Wallpaper-generated colors for SwayNC
 * Auto-generated by color-gen.sh — DO NOT EDIT MANUALLY */

@define-color noti-border-color   ${OUTLINE_VARIANT};
@define-color noti-bg             ${SURFACE_CONTAINER};
@define-color noti-bg-hover-alt   ${SURFACE_CONTAINER_HIGH};
@define-color noti-bg-alt         ${SURFACE_CONTAINER_LOW};
@define-color noti-fg             ${ON_SURFACE};
@define-color noti-bg-hover       ${SURFACE_CONTAINER_HIGH};
@define-color noti-bg-focus       ${SURFACE_CONTAINER_HIGH};
@define-color noti-close-bg       ${SURFACE_VARIANT};
@define-color noti-close-bg-hover ${SURFACE_CONTAINER_HIGHEST};
@define-color noti-urgent         ${ERROR};
@define-color bg-selected         ${PRIMARY};
EOF
echo "[color-gen] ✓ SwayNC colors written"

# ── Hyprland ──────────────────────────────────────────────────────────────────
cat > "$HYPR_COLORS" << EOF
-- Wallpaper-generated colors for Hyprland
-- Auto-generated by color-gen.sh — DO NOT EDIT MANUALLY
-- Source: $WALLPAPER

Theme = {
    primary              = "${PRIMARY}",
    on_primary           = "${ON_PRIMARY}",
    primary_container    = "${PRIMARY_CONTAINER}",
    secondary            = "${SECONDARY}",
    tertiary             = "${TERTIARY}",
    background           = "${BACKGROUND}",
    on_background        = "${ON_BACKGROUND}",
    surface              = "${SURFACE}",
    error                = "${ERROR}",
    outline              = "${OUTLINE}",
    -- Hyprland rgba() border format
    active_border_1      = "$(to_rgba "$PRIMARY")",
    active_border_2      = "$(to_rgba "$SECONDARY")",
    inactive_border      = "$(to_rgba "$OUTLINE_VARIANT" "55")",
    shadow_color         = "$(to_rgba "$BACKGROUND" "ee")",
}
EOF
echo "[color-gen] ✓ Hyprland colors written"

# ── Hyprlock ──────────────────────────────────────────────────────────────────
cat > "$HYPRLOCK_COLORS" << EOF
# Wallpaper-generated colors for Hyprlock
# Auto-generated by color-gen.sh — DO NOT EDIT MANUALLY

\$hl_primary    = ${PRIMARY}
\$hl_on_primary = ${ON_PRIMARY}
\$hl_surface    = ${SURFACE_CONTAINER}
\$hl_on_surface = ${ON_SURFACE}
\$hl_error      = ${ERROR}
EOF
echo "[color-gen] ✓ Hyprlock colors written"

# Cache current wallpaper path
echo "$WALLPAPER" > "$THEME_CACHE"
echo "[color-gen] ✓ All done."
