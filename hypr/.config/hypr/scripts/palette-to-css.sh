#!/usr/bin/env bash

##
# palette-to-css.sh — Convert a named rofi .rasi palette into waybar/swaync/hyprland
# color files so all apps stay in sync when using preset palettes.
# Usage: palette-to-css.sh <palette.rasi_path> <palette_name>
##

set -euo pipefail

RASI_FILE="${1:-}"
PALETTE_NAME="${2:-unknown}"

WAYBAR_COLORS="$HOME/.config/waybar/colors.css"
SWAYNC_COLORS="$HOME/.config/swaync/colors.css"
HYPR_COLORS="$HOME/.config/hypr/themes/colors.lua"
HYPRLOCK_COLORS="$HOME/.config/hypr/themes/hyprlock-colors.conf"

[[ -z "$RASI_FILE" || ! -f "$RASI_FILE" ]] && { echo "ERROR: rasi file not found" >&2; exit 1; }

# Extract hex values from the rasi file
get_rasi_color() {
    local key="$1"
    grep -oP "${key}\s*:\s*\K#[0-9a-fA-F]{6,8}" "$RASI_FILE" 2>/dev/null | head -1 || echo "#888888"
}

BG=$(get_rasi_color "background")
BG_ALT=$(get_rasi_color "background-alt")
BG_SURFACE=$(get_rasi_color "background-surface")
FG=$(get_rasi_color "foreground")
FG_ALT=$(get_rasi_color "foreground-alt")
SELECTED=$(get_rasi_color "selected")
SELECTED_TEXT=$(get_rasi_color "selected-text")
ACTIVE=$(get_rasi_color "active")
URGENT=$(get_rasi_color "urgent")
BORDER=$(get_rasi_color "border-color")

# Strip trailing FF alpha if present (for CSS use)
strip_alpha() { echo "${1:0:7}"; }

BG_CSS=$(strip_alpha "$BG")
BG_ALT_CSS=$(strip_alpha "$BG_ALT")
BG_SURFACE_CSS=$(strip_alpha "$BG_SURFACE")
FG_CSS=$(strip_alpha "$FG")
FG_ALT_CSS=$(strip_alpha "$FG_ALT")
SELECTED_CSS=$(strip_alpha "$SELECTED")
SELECTED_TEXT_CSS=$(strip_alpha "$SELECTED_TEXT")
ACTIVE_CSS=$(strip_alpha "$ACTIVE")
URGENT_CSS=$(strip_alpha "$URGENT")
BORDER_CSS=$(strip_alpha "$BORDER")

# ── Waybar ────────────────────────────────────────────────────────────────────
cat > "$WAYBAR_COLORS" << EOF
/* Palette-based colors for Waybar — $PALETTE_NAME
 * Auto-generated by palette-to-css.sh — DO NOT EDIT MANUALLY */

@define-color wb-bg              ${BG_CSS};
@define-color wb-bg-alt          ${BG_ALT_CSS};
@define-color wb-fg              ${FG_CSS};
@define-color wb-fg-alt          ${FG_ALT_CSS};
@define-color wb-primary         ${SELECTED_CSS};
@define-color wb-secondary       ${ACTIVE_CSS};
@define-color wb-tertiary        ${ACTIVE_CSS};
@define-color wb-urgent          ${URGENT_CSS};
@define-color wb-border          ${BORDER_CSS};
@define-color wb-active-ws       ${SELECTED_CSS};
@define-color wb-active-ws-text  ${SELECTED_TEXT_CSS};
EOF

# ── SwayNC ────────────────────────────────────────────────────────────────────
cat > "$SWAYNC_COLORS" << EOF
/* Palette-based colors for SwayNC — $PALETTE_NAME
 * Auto-generated by palette-to-css.sh — DO NOT EDIT MANUALLY */

@define-color noti-border-color   ${BORDER_CSS};
@define-color noti-bg             ${BG_ALT_CSS};
@define-color noti-bg-hover-alt   ${BG_CSS};
@define-color noti-bg-alt         ${BG_SURFACE_CSS};
@define-color noti-fg             ${FG_CSS};
@define-color noti-bg-hover       ${BG_ALT_CSS};
@define-color noti-bg-focus       ${BG_ALT_CSS};
@define-color noti-close-bg       ${BG_ALT_CSS};
@define-color noti-close-bg-hover ${BG_CSS};
@define-color noti-urgent         ${URGENT_CSS};
@define-color bg-selected         ${SELECTED_CSS};
EOF

# ── Hyprland ──────────────────────────────────────────────────────────────────
hex_to_rgba() {
    local hex="${1#\#}"
    local alpha="${2:-ee}"
    echo "rgba(${hex}${alpha})"
}

cat > "$HYPR_COLORS" << EOF
-- Palette-based colors for Hyprland — $PALETTE_NAME
-- Auto-generated by palette-to-css.sh — DO NOT EDIT MANUALLY

Theme = {
    primary           = "${SELECTED_CSS}",
    on_primary        = "${SELECTED_TEXT_CSS}",
    primary_container = "${BG_ALT_CSS}",
    secondary         = "${ACTIVE_CSS}",
    tertiary          = "${ACTIVE_CSS}",
    background        = "${BG_CSS}",
    on_background     = "${FG_CSS}",
    surface           = "${BG_ALT_CSS}",
    error             = "${URGENT_CSS}",
    outline           = "${BORDER_CSS}",
    active_border_1   = "$(hex_to_rgba "$SELECTED_CSS")",
    active_border_2   = "$(hex_to_rgba "$ACTIVE_CSS")",
    inactive_border   = "$(hex_to_rgba "$BG_ALT_CSS" "55")",
    shadow_color      = "$(hex_to_rgba "$BG_CSS" "ee")",
}
EOF

# ── Hyprlock ──────────────────────────────────────────────────────────────────
cat > "$HYPRLOCK_COLORS" << EOF
# Palette-based colors for Hyprlock — $PALETTE_NAME
# Auto-generated by palette-to-css.sh — DO NOT EDIT MANUALLY

\$hl_primary    = ${SELECTED_CSS}
\$hl_on_primary = ${SELECTED_TEXT_CSS}
\$hl_surface    = ${BG_ALT_CSS}
\$hl_on_surface = ${FG_CSS}
\$hl_error      = ${URGENT_CSS}
EOF

echo "[palette-to-css] ✓ Colors written for palette: $PALETTE_NAME"
